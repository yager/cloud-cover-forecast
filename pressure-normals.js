// 一番近い代表地点の都道府県インデックスを返す（PREFECTURE_COORDS・PREFECTURESと同じ並び）。
// 日本付近だけを想定した単純な二乗距離。経度1度は緯度1度よりやや短いので cos(緯度) で補正する
export function nearestPrefectureIndex(lat, lng) {
    let best = 0;
    let bestDist = Infinity;
    for (let i = 0; i < PREFECTURE_COORDS.length; i++) {
        const [plat, plon] = PREFECTURE_COORDS[i];
        const dlat = lat - plat;
        const dlng = (lng - plon) * Math.cos(plat * Math.PI / 180);
        const dist = dlat * dlat + dlng * dlng;
        if (dist < bestDist) {
            bestDist = dist;
            best = i;
        }
    }
    return best;
}
